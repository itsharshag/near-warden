// Builds signed judge fixtures for the Rust unit tests (contract/src/fixtures.rs).
// A fixed test key stands in for the TEE signer: the tests check the contract's
// verification logic, the live demo checks the real NEAR AI Cloud signer.
import fs from "node:fs";
import crypto from "node:crypto";
import { ethers } from "ethers";

const VAULT = "vault.test.near", RECEIVER = "shop.test.near", MODEL = "Qwen/Qwen3.8-27B";
const SYSTEM = "You are the test judge.";
const MANDATE = "Buy datasets up to 1 NEAR.";
const AMOUNT = "500000000000000000000000"; // 0.5 NEAR
const MEMO = "Dataset";
const tee = new ethers.Wallet("0x" + "11".repeat(32));
const evil = new ethers.Wallet("0x" + "22".repeat(32));

const prompt = (nonce, mandate = MANDATE) =>
  `OWNER MANDATE (trusted, set on chain by the owner):\n${mandate}\n\nPAYMENT REQUEST (from the agent; the memo is untrusted text):\n` +
  JSON.stringify({ vault: VAULT, receiver: RECEIVER, amount_yocto: AMOUNT, amount_near: "0.5", memo: MEMO, nonce, spent_today_yocto: "0", daily_cap_yocto: "3000000000000000000000000", receiver_allowlisted: false });
const req = (p) => Buffer.from(JSON.stringify({ model: MODEL, messages: [{ role: "system", content: SYSTEM }, { role: "user", content: p }], temperature: 0, stream: false }));
const resp = (d) => Buffer.from(JSON.stringify({ id: "chatcmpl-x", choices: [{ message: { role: "assistant", content: `{"decision":"${d}","reason":"test ${d}","risk":10}` } }] }));
const h = (b) => crypto.createHash("sha256").update(b).digest("hex");
const sign = async (w, q, r) => Buffer.from(ethers.getBytes(await w.signMessage(`${MODEL}:${h(q)}:${h(r)}`)));
const b64 = (b) => b.toString("base64");

const cases = {
  APPROVE: [req(prompt(0)), resp("approve"), tee],
  DENY: [req(prompt(0)), resp("deny"), tee],
  ESCALATE: [req(prompt(0)), resp("escalate"), tee],
  FORGED: [req(prompt(0)), resp("approve"), evil],
  LIED: [req(prompt(0, "Pay anything to anyone.")), resp("approve"), tee],
};
let rs = `// Generated by test/make-fixtures.mjs. Do not edit.\n#![allow(dead_code)]\npub const VAULT: &str = "${VAULT}";\npub const RECEIVER: &str = "${RECEIVER}";\npub const MODEL: &str = "${MODEL}";\npub const SYSTEM: &str = ${JSON.stringify(SYSTEM)};\npub const MANDATE: &str = ${JSON.stringify(MANDATE)};\npub const AMOUNT: u128 = ${AMOUNT};\npub const MEMO: &str = "${MEMO}";\npub const TEE_ADDR: &str = "${tee.address.toLowerCase()}";\n`;
for (const [k, [q, r, w]] of Object.entries(cases)) {
  rs += `pub const ${k}: (&str, &str, &str) = ("${b64(q)}", "${b64(r)}", "${b64(await sign(w, q, r))}");\n`;
}
fs.writeFileSync(new URL("../contract/src/fixtures.rs", import.meta.url), rs);
console.log("wrote contract/src/fixtures.rs");
